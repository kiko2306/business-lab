    {
        // validate
        $this->validate($request, [
            'code' => 'required|string',
            'name' => 'required|string',
        ]);

        // get old default language
        $old_default = Language::where('default', true)->first();
        $old_default->default = false;
        $old_default->save();

        // get new default language
        $new_default = Language::where('code', $request->code)->first();
        $new_default->default = true;
        $new_default->save();
    }

